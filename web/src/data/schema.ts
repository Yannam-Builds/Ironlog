import { z } from "zod";
const id = z.string().min(1).max(200);
const number = z.number().finite().nonnegative();
const tracking = z.string();
const metadata = {
  primaryMuscles: z.array(z.string()).optional(),
  muscleContributions: z.record(z.string(), number).optional(),
  category: z.string().optional(),
  isBodyweight: z.boolean().optional(),
  requiresExternalLoad: z.boolean().optional(),
  movementPattern: z.string().optional(),
  difficulty: z.string().optional(),
};
export const exerciseSchema = z.object({
  ...metadata,
  id,
  name: z.string().min(1),
  muscle: z.string(),
  equipment: z.string(),
  tracking,
  secondaryMuscles: z.array(z.string()).optional(),
  aliases: z.array(z.string()).optional(),
  custom: z.boolean().optional(),
});
const planned = z.object({
  id,
  exerciseId: z.string(),
  name: z.string().min(1),
  sets: z.number().int().min(1).max(1000),
  reps: z.string(),
  restSeconds: number,
  notes: z.string(),
  supersetGroup: z.string(),
  isWarmup: z.boolean(),
});
export const planSchema = z.object({
  id,
  name: z.string().min(1),
  description: z.string(),
  goal: z.string(),
  days: z.array(
    z.object({
      id,
      name: z.string(),
      color: z.string(),
      exercises: z.array(planned),
    }),
  ),
  order: z.number().finite(),
  templateId: z.string().optional(),
  progressionRules: z.object({
    progressionModel: z.string(), blockLengthWeeks: z.number().int().min(1).max(52),
    currentWeek: z.number().int().min(1).max(52), deloadEveryWeeks: z.number().int().min(1).max(52),
    percent1RM: z.number().int().min(50).max(95), rpeTarget: z.number().int().min(1).max(10),
    rirTarget: z.number().int().min(0).max(10),
  }).optional(),
  exerciseProgressionOverrides: z.record(z.string(), z.string()).optional(),
});
export const workoutSchema = z.object({
  id,
  planId: z.string().optional(),
  dayId: z.string().optional(),
  name: z.string(),
  startedAt: number,
  completedAt: number.optional(),
  durationSeconds: number.optional(),
  status: z.enum(["active", "completed", "discarded"]),
  notes: z.string(),
  rating: number.optional(),
  restEndsAt: number.optional(),
  restUsed: z.boolean(),
  revision: z.number().int().nonnegative(),
  imported: z.boolean().optional(),
  exercises: z.array(
    planned.extend({
      ...metadata,
      tracking,
      muscle: z.string(),
      equipment: z.string(),
      secondaryMuscles: z.array(z.string()).optional(),
      pendingWarmups: z.array(z.object({ id, weightKg: number, reps: number })),
      loggedSets: z.array(
        z.object({
          id,
          weightKg: number,
          reps: number,
          durationSeconds: number,
          distanceKm: number,
          kind: z.enum(["normal", "warmup", "failure", "drop", "amrap"]),
          rpe: z.number().min(0).max(10).optional(),
          rir: number.optional(),
          toFailure: z.boolean().optional(),
          notes: z.string(),
          loggedAt: number,
        }),
      ),
    }),
  ),
});
const trainingSignalsSchema = z.object({
  strength: z.number().int().min(0).max(999),
  power: z.number().int().min(0).max(999),
  hypertrophy: z.number().int().min(0).max(999),
  endurance: z.number().int().min(0).max(999),
  agility: z.number().int().min(0).max(999),
  discipline: z.number().int().min(0).max(999),
  recovery: z.number().int().min(0).max(999),
});
const onboardingLedgerBaselineSchema = z.object({
  version: z.literal(1),
  provenance: z.literal("onboarding_self_report"),
  formula: z.literal("trainingAgeMonths*4.345*historicalTrainingDaysPerWeek"),
  trustScore: z.literal(0.5),
  estimatedLifetimeSessions: z.number().int().nonnegative(),
  xp: z.number().int().nonnegative(),
  grade: z.enum(["Uncalibrated", "Graphite", "Iron", "Steel", "Titanium"]),
  stats: trainingSignalsSchema,
  supportedBadgeIds: z.array(
    z.enum([
      "first_workout",
      "workouts_10",
      "workouts_50",
      "workouts_100",
      "consistency_4w",
      "member_365",
    ]),
  ),
  seededAt: number,
});
export const profileSchema = z.object({
  name: z.string(),
  age: number,
  yearOfBirth: z.number().int().min(1900).max(3000).default(2000),
  heightCm: number,
  weightKg: number,
  goalWeightKg: z.number().positive().optional(),
  measurementGoals: z.record(z.string(), z.number().positive()).default({}),
  onboardingBodyweightKg: z.number().positive().optional(),
  experience: z.string(),
  goal: z.string(),
  progressionStyle: z.string().default("LINEAR"),
  goalMode: z.string().default("STRENGTH"),
  selectedTrainingDays: z.array(z.number().int().min(0).max(6)).min(1).default([0, 2, 4]),
  trainingAgeMonths: z.number().int().nonnegative().default(0),
  historicalTrainingDaysPerWeek: z.number().int().min(1).max(7).default(3),
  hasPastTraining: z.boolean().default(false),
  hasGymAccess: z.boolean().default(true),
  baselinePushups: z.number().int().nonnegative().default(0),
  baselinePullups: z.number().int().nonnegative().default(0),
  baselineBenchKg: z.number().int().nonnegative().default(0),
  baselineLatPulldownKg: z.number().int().nonnegative().default(0),
  baselineMileRunSeconds: z.number().int().nonnegative().default(0),
  weeklyGoal: z.number().int().min(1).max(7),
  sessionMinutes: number,
  coaching: z.string(),
  onboardingStep: z.number().int().nonnegative(),
  onboarded: z.boolean(),
  activePlanId: z.string().optional(),
  theme: z.string(),
  unit: z.enum(["kg", "lb"]),
  effort: z.enum(["rpe", "rir"]),
  restSeconds: number,
  barKg: number,
  platesKg: z.array(z.number().positive()),
  plateInventory: z.array(z.object({ weightKg: z.number().finite().positive(), quantity: z.number().int().nonnegative() })).optional(),
  keepAwake: z.boolean(),
  planExerciseNotesVisible: z.boolean().default(true),
  exerciseNextNotes: z.record(z.string().regex(/^exercise_next_note:.+$/), z.string().max(4000)).optional(),
  badgeUnlocks: z.record(z.string(), number),
  ledgerBaseline: onboardingLedgerBaselineSchema.optional(),
  recoveryWeeks: z.array(z.string()),
  lastBackupAt: number.optional(),
});
export const snapshotSchema = z.object({
  profile: profileSchema,
  plans: z.array(planSchema),
  workouts: z.array(workoutSchema),
  exercises: z.array(exerciseSchema),
  measurements: z.array(
    z.object({
      id,
      date: z.string(),
      type: z.string(),
      value: number,
      unit: z.string(),
    }),
  ),
  photos: z.array(
    z.object({
      id,
      date: z.string(),
      capturedAt: number.optional(),
      notes: z.string(),
      blob: z.instanceof(Blob),
    }),
  ),
  checkins: z.array(
    z.object({
      id,
      at: number,
      soreness: z.number().int().min(0).max(5),
      sleep: z.number().int().min(0).max(5),
      energy: z.number().int().min(0).max(5),
      painRegions: z.array(z.string()),
      notes: z.string().optional(),
    }),
  ),
  gyms: z.array(
    z.object({
      id,
      name: z.string(),
      barKg: number,
      platesKg: z.array(z.number().positive()),
      plateInventory: z.array(z.object({ weightKg: z.number().finite().positive(), quantity: z.number().int().nonnegative() })).optional(),
    }),
  ),
});
